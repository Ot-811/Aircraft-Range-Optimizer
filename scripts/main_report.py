        ["Raymer wing mass at 737-800 geometry", f"{fmt(cal['W_wing_737_kg'])} kg, so W_fixed = {fmt(cal['W_fixed_kg'])} kg"],
        ["Fuel-volume coefficient k_f", f"{cal['k_f']:.2f} kg/m³"],
