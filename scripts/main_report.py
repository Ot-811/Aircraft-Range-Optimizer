def names(active):
    return ", ".join(NAMES.get(a, a) for a in active) or "none"


def pct(a, b):
    """Percentage change from b to a."""
    return 100 * (a / b - 1)


def sci(v):
    """1.8e-08 -> '1.8·10⁻⁸'."""
    if v == 0 or not math.isfinite(v):
        return "0" if v == 0 else "-"
    e = math.floor(math.log10(abs(v)))
    sup = str(e).translate(str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹"))
    return f"{v / 10 ** e:.1f}·10{sup}"


def num(v):
    """Readable parameter value: 79,016 / 0.0937 / 2,500."""
    return fmt(v) if abs(v) >= 1000 else f"{v:.4g}"


