            [[lab] + [fmt(d[k], nd) for d in (base, opt, opt36)] for lab, k, nd in rows]
            + [["Active constraints", "fuel volume", names(act), names(act36)]],
            caption=f"Range gain: {pct(opt['range_km'], base['range_km']):+.2f} % (no span limit), "
