"""DEMO REPORT. Builds demo_reports/<name>/report.md and report.pdf from that run's results.json.

    python scripts/demo_report.py demo_reports/<name>     # rebuild one demo report

scripts/demo.py calls this automatically. It is separate from the main report
(scripts/main_report.py): the demo report is short and is about ONE design question.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from aircraft_opt.report_writer import Report, fmt  # noqa: E402
from aircraft_opt.params import calibrated_params, B737  # noqa: E402

NAMES = {"mtow": "MTOW", "stall": "stall speed", "fuel_volume": "fuel volume", "mach": "Mach limit",
         "span": "gate span", "weight_buildup": "weight build-up"}
MEANING = {"mtow": "raising the maximum take-off mass by 1 %",
           "stall": "allowing a 1 % higher wing loading (slightly higher stall speed)",
           "fuel_volume": "making the fuel tanks 1 % bigger",
           "mach": "raising the Mach limit by 1 %",
           "span": "allowing a 1 % longer wingspan"}
DEFAULT_START_FUEL = 17_000.0      # kg, the demo's default starting cruise fuel (used by demo.py)
SOLVERS = {"gd": "gradient descent", "newton": "Newton", "modnewton": "modified Newton",
           "bfgs": "BFGS", "sr1": "SR1"}


def build_demo_report(run_dir) -> str:
    run_dir = Path(run_dir)
    R = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    I, st, b7, op, ch = R["inputs"], R["start"], R["b737"], R["optimum"], R["checks"]

    r = Report(f"Aircraft range optimiser: demo run '{I['name']}'",
               f"Generated by scripts/demo_report.py on {R['date']}. Augmented Lagrangian + "
               f"{SOLVERS[I['solver']]} (our own code), checked with SciPy SLSQP.")

    # ------------------------------------------------------------------ inputs
    r.heading("Your inputs")
    d = calibrated_params()                    # the defaults the demo offers
    r.table(["Input", "Value", "737-800 default"], [
        ["Passengers (100 kg each incl. bags)", I["passengers"], B737["pax"]],
        ["Maximum take-off mass [kg]", fmt(I["MTOW_kg"]), fmt(d.MTOW)],
        ["Cruise altitude [ft]", fmt(I["altitude_ft"]), fmt(B737["h_cruise_ft"])],
        ["Engine fuel burn factor", I["engine_factor"], 1.0],
        ["Maximum stall speed [m/s]", I["max_stall_speed"], d.V_stall_max],
        ["Maximum cruise Mach", I["max_Mach"], d.M_max],
        ["Wing structure factor", I["wing_structure_factor"], 1.0],
        ["Maximum wingspan [m]", I["max_wingspan_m"] or "no limit", "no limit"],
        ["Start: wingspan [m]", I["start_wingspan_m"], B737["span"]],
        ["Start: wing area [m²]", I["start_wing_area_m2"], B737["S"]],
        ["Start: cruise Mach", I["start_Mach"], B737["M_cruise"]],
        ["Start: cruise fuel [kg]", fmt(I["start_cruise_fuel_kg"]), fmt(DEFAULT_START_FUEL)],
    ])

    # ------------------------------------------------------------------ designs
    r.heading("Designs")
    cols = [("Your start", st), ("737-800", b7), ("Optimum" if R["feasible"] else "Best attempt", op)]
    cols = [(n, d) for n, d in cols if d is not None]
    rows = [("Range [km]", "range_km", 0), ("Wingspan [m]", "span", 1), ("Wing area [m²]", "S", 1),
            ("Aspect ratio", "AR", 2), ("Cruise Mach", "Mach", 3), ("Cruise fuel [kg]", "W_fuel", 0),
            ("Initial mass [kg]", "W_i", 0), ("Wing mass [kg]", "W_wing", 0),
            ("Tank capacity [kg]", "fuel_capacity", 0), ("L/D", "LD", 2), ("Stall speed [m/s]", "V_stall", 1)]
    r.table([""] + [n for n, _ in cols], [[lab] + [fmt(d[k], nd) for _, d in cols] for lab, k, nd in rows])
    if b7 is not None:
        r.para("The 737-800 column is the real 737-800 (its own wing and wing mass) at Mach 0.785, flown "
               "under YOUR requirements with as much fuel as its tanks and the MTOW allow.")
    else:
        r.para("The 737-800 cannot carry this payload within this MTOW, so it is not shown.")

    sv = R["start_violations"]
    if sv:
        r.para("**Your starting design is NOT allowed.** It breaks: "
               + ", ".join(f"{k} (by {v:.1f} %)" for k, v in sv.items())
               + ". Its range is what it would fly, but it is not an acceptable aircraft.")
    else:
        r.para("Your starting design satisfies every constraint.")
    if b7 is not None and R["b737_violations"]:
        r.para("Under these requirements the 737-800 itself breaks: " + ", ".join(R["b737_violations"]) + ".")

    # ------------------------------------------------------------------ result
    r.heading("Result")
    s = R["solver"]
    if not R["feasible"]:
        r.para(f"**No design satisfies all the requirements** (smallest violation reached "
               f"{R['max_violation']:.1e}). The requirements contradict each other, e.g. too much payload "
               "for the MTOW, or a stall speed so low that no wing within the bounds meets it.")
    else:
        lines = [f"**Optimised range: {fmt(op['range_km'])} km** "
                 f"({op['range_km'] - st['range_km']:+,.0f} km vs your start"
                 + (", which was not allowed" if sv else "") + ")."]
        if b7 is not None:
            lines.append(f"Versus the 737-800 under the same requirements: {op['range_km'] - b7['range_km']:+,.0f} km "
                         f"({100 * (op['range_km'] / b7['range_km'] - 1):+.1f} %).")
        lines.append(f"Solver: converged = {s['converged']}, {s['outer_it']} outer / {s['inner_it']} inner "
                     f"iterations, {s['time_s']:.2f} s.")
        r.bullets(lines)
    r.figure(run_dir / "fig_history.png", "Range and constraint violation at every outer iteration "
             "(0 = your start). An infeasible start can fly 'further' until the violation is forced to zero.")

    # ------------------------------------------------------------------ checks
    if R["feasible"]:
        r.heading("Is it really the optimum? Independent checks")
        k = ch["kkt"]
        starts = [x for x in ch["random_start_ranges_km"] if x is not None]
        best = ch["best_random_km"]
        r.table(["Check", "Result", "Passed"], [
            ["1. SciPy SLSQP from your start",
             f"{fmt(ch['slsqp_range_km'], 1)} km" if ch["slsqp_range_km"] else "failed",
             "yes" if ch["slsqp_range_km"] and abs(ch["slsqp_range_km"] - op["range_km"]) < 0.5 else "NO"],
            ["2. Our solver from 5 random starts", ", ".join(fmt(x, 1) for x in starts) + " km",
             "yes" if len(starts) == 5 and max(abs(x - op["range_km"]) for x in starts) < 0.5 else "NO"],
            [f"3. {ch['n_random_feasible']:,} random allowed designs (of {ch['n_random']:,})",
             f"best {fmt(best)} km" if best else "none found",
             "yes" if best is None or best <= op["range_km"] + 1e-6 else "NO"],
            ["4. KKT: stationarity / complementarity",
             f"{k['stationarity']:.1e} / {k['complementarity']:.1e}",
             "yes" if k["stationarity"] < 1e-5 and k["complementarity"] < 1e-5 and k["min_multiplier"] >= -1e-8 else "NO"],
            ["5. Second-order condition",
             ", ".join(f"{e:+.3f}" for e in k["reduced_hessian_eigs"]) or "vertex (no free directions)",
             "yes" if all(e > 0 for e in k["reduced_hessian_eigs"]) else "NO"],
        ])
        r.para("Checks 1-3 are numerical evidence that the optimum is global within the bounds, not a proof. "
               "Checks 4-5 show it is a strict local minimum.")
        if (run_dir / "fig_random_designs.png").is_file():
            r.figure(run_dir / "fig_random_designs.png", "Random allowed designs (grey) vs the optimum (star).")

        r.heading("What limits the range")
        act = [(n, v) for n, v in k["multipliers"].items() if n in MEANING and v > 1e-6]
        if act:
            r.para("Each active constraint has a KKT multiplier λ. Because the objective is −ln R and every "
                   "constraint is normalised, λ is the % range gained per 1 % relaxation:")
            r.bullets([f"**{NAMES[n]}** (λ = {v:.3f}): {MEANING[n]} gives about {v:+.2f} % range"
                       for n, v in act])
        free = [NAMES[n] for n in ("mtow", "stall", "fuel_volume") if n not in dict(act)]
        if free:
            r.para("Not limiting (multiplier 0): " + ", ".join(free) + ".")

    r.heading("Limits of this model")
    r.para("Conceptual model calibrated on the 737-800: Breguet cruise, no wave drag (Mach cap instead), "
           "empirical wing mass and tank volume. Numbers are model predictions, not a validated aircraft.")
    return r.save(run_dir, "report")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    if len(sys.argv) != 2:
        sys.exit("usage: python scripts/demo_report.py demo_reports/<name>")
    print(build_demo_report(sys.argv[1]))
